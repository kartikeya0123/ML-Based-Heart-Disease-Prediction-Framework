import { useState, useEffect } from "react";
import { Logo } from "@/components/Logo";
import { BackgroundOrbs } from "@/components/BackgroundOrbs";
import { GlassCard } from "@/components/GlassCard";
import { Button } from "@/components/Button";
import { RiskMeter } from "@/components/RiskMeter";
import { FeatureContributions } from "@/components/FeatureContributions";
import { WhatIfSimulator } from "@/components/WhatIfSimulator";
import { useSessionHistory } from "@/hooks/useSessionHistory";
import type { PatientInput, PredictionResult, SessionPrediction } from "@/types";
import { CATEGORICAL_OPTIONS } from "@/types";
import {
  ArrowLeft, Brain, Lightbulb, TrendingUp, FileText, Download,
  Activity, ShieldCheck, Cpu, Clock, RefreshCw, Trash2, ChevronRight,
  User, HeartPulse, AlertTriangle
} from "lucide-react";

interface ResultsPageProps {
  input: PatientInput;
  result: PredictionResult;
  onBack: () => void;
  onNewAssessment: () => void;
}

type Tab = "overview" | "explanation" | "whatif" | "history";

export function ResultsPage({ input, result, onBack, onNewAssessment }: ResultsPageProps) {
  const [tab, setTab] = useState<Tab>("overview");
  const { predictions, addPrediction, clearHistory } = useSessionHistory();

  useEffect(() => {
    const sessionPred: SessionPrediction = {
      ...result,
      id: Math.random().toString(36).substring(2, 12),
    };
    addPrediction(sessionPred);
  }, [result, addPrediction]);

  const riskClass =
    result.riskLevel === "Low" ? "risk-low" :
    result.riskLevel === "Moderate" ? "risk-moderate" :
    result.riskLevel === "High" ? "risk-high" : "risk-veryhigh";

  const handleDownloadReport = () => {
    const lines: string[] = [
      "CARDIOSENSE AI",
      "CARDIOVASCULAR RISK ASSESSMENT REPORT",
      "=" .repeat(50),
      "",
      `Assessment Timestamp: ${new Date(result.timestamp).toLocaleString()}`,
      `Model Version: ${result.modelVersion}`,
      "",
      "PATIENT INPUT PROFILE",
      "-" .repeat(30),
      `Patient Name: ${input.name || "Not provided"}`,
      `Age: ${input.age} years`,
      `Biological Sex: ${input.sex === 1 ? "Male" : "Female"}`,
      `Chest Pain Type: ${CATEGORICAL_OPTIONS.chestPainType[input.chestPainType]}`,
      `Resting Blood Pressure: ${input.restingBP} mmHg`,
      `Cholesterol: ${input.cholesterol} mg/dL`,
      `Fasting Blood Sugar > 120: ${input.fastingBS === 1 ? "Yes" : "No"}`,
      `Resting ECG: ${CATEGORICAL_OPTIONS.restingECG[input.restingECG]}`,
      `Max Heart Rate: ${input.maxHR} bpm`,
      `Exercise Induced Angina: ${input.exerciseAngina === 1 ? "Yes" : "No"}`,
      `Oldpeak: ${input.oldpeak}`,
      `ST Slope: ${CATEGORICAL_OPTIONS.stSlope[input.stSlope]}`,
      "",
      "PREDICTION RESULTS",
      "-" .repeat(30),
      `Estimated Model Risk: ${result.riskScore.toFixed(1)}%`,
      `Risk Category: ${result.riskLevel}`,
      `Model Probability: ${(result.probability * 100).toFixed(2)}%`,
      "",
      "PREDICTION INTERPRETATION",
      "-" .repeat(30),
      result.prediction,
      "",
      "KEY CONTRIBUTING FEATURES",
      "-" .repeat(30),
      ...result.contributions.slice(0, 6).map((c, i) =>
        `${i + 1}. ${c.label} (value=${c.value}): impact=${c.impact >= 0 ? "+" : ""}${c.impact.toFixed(4)}`
      ),
      "",
      "RECOMMENDATIONS",
      "-" .repeat(30),
      ...result.recommendations.map((r, i) => `${i + 1}. ${r}`),
      "",
      "RESPONSIBLE AI DISCLAIMER",
      "-" .repeat(30),
      "CardioSense AI produces machine-learning-based estimates from structured",
      "input data. It does not provide definitive medical diagnosis, treatment",
      "recommendations, or professional medical advice. Model predictions should",
      "be interpreted within the limitations of the underlying dataset,",
      "preprocessing pipeline, trained model, and validation methodology.",
      "AI can assist understanding. Clinical decisions belong to qualified",
      "healthcare professionals.",
      "",
      "=" .repeat(50),
      "Generated by CardioSense AI",
    ];

    const blob = new Blob([lines.join("\n")], { type: "text/plain" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `cardiosense-report-${Date.now()}.txt`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const inputFields = [
    { label: "Name", value: input.name || "Not provided", icon: <User className="w-4 h-4" /> },
    { label: "Age", value: `${input.age} years`, icon: <User className="w-4 h-4" /> },
    { label: "Sex", value: input.sex === 1 ? "Male" : "Female", icon: <User className="w-4 h-4" /> },
    { label: "Chest Pain", value: CATEGORICAL_OPTIONS.chestPainType[input.chestPainType], icon: <HeartPulse className="w-4 h-4" /> },
    { label: "Resting BP", value: `${input.restingBP} mmHg`, icon: <Activity className="w-4 h-4" /> },
    { label: "Cholesterol", value: `${input.cholesterol} mg/dL`, icon: <Activity className="w-4 h-4" /> },
    { label: "Fasting BS", value: input.fastingBS === 1 ? "Yes" : "No", icon: <Activity className="w-4 h-4" /> },
    { label: "Resting ECG", value: CATEGORICAL_OPTIONS.restingECG[input.restingECG], icon: <Activity className="w-4 h-4" /> },
    { label: "Max HR", value: `${input.maxHR} bpm`, icon: <HeartPulse className="w-4 h-4" /> },
    { label: "Exercise Angina", value: input.exerciseAngina === 1 ? "Yes" : "No", icon: <AlertTriangle className="w-4 h-4" /> },
    { label: "Oldpeak", value: String(input.oldpeak), icon: <Activity className="w-4 h-4" /> },
    { label: "ST Slope", value: CATEGORICAL_OPTIONS.stSlope[input.stSlope], icon: <Activity className="w-4 h-4" /> },
  ];

  return (
    <div className="min-h-screen relative overflow-hidden">
      <BackgroundOrbs />

      <div className="relative z-10">
        {/* Header */}
        <header className="px-6 md:px-12 py-6 flex items-center justify-between">
          <Logo size="md" />
          <div className="flex gap-3">
            <button onClick={onBack} className="btn-ghost px-4 py-2.5 rounded-xl text-sm font-medium flex items-center gap-2">
              <ArrowLeft className="w-4 h-4" /> Back
            </button>
            <button onClick={onNewAssessment} className="btn-primary px-4 py-2.5 rounded-xl text-sm font-medium flex items-center gap-2">
              <RefreshCw className="w-4 h-4" /> New Assessment
            </button>
          </div>
        </header>

        <div className="px-6 md:px-12 pb-16 max-w-6xl mx-auto">
          {/* Title */}
          <div className="mb-6 fade-in-up">
            <h1 className="text-2xl md:text-3xl font-bold text-slate-800 mb-1">
              Cardiovascular Intelligence Report
            </h1>
            <p className="text-slate-500">Complete AI-powered assessment with explanation and exploration</p>
          </div>

          {/* Top stat cards */}
          <div className="grid grid-cols-3 gap-4 mb-6">
            <GlassCard className="p-5 text-center fade-in-up" style={{ animationDelay: "0s" }}>
              <div>
                <div className="w-10 h-10 rounded-xl gradient-bg flex items-center justify-center mx-auto mb-3">
                  <TrendingUp className="w-5 h-5 text-white" />
                </div>
                <p className="text-2xl font-bold text-slate-800">{result.riskScore.toFixed(1)}%</p>
                <p className="text-xs text-slate-400 mt-1">Risk Score</p>
              </div>
            </GlassCard>
            <GlassCard className="p-5 text-center fade-in-up" style={{ animationDelay: "0.05s" }}>
              <div>
                <div className={`w-10 h-10 rounded-xl ${riskClass} flex items-center justify-center mx-auto mb-3`}>
                  <AlertTriangle className="w-5 h-5 text-white" />
                </div>
                <p className="text-2xl font-bold text-slate-800">{result.riskLevel}</p>
                <p className="text-xs text-slate-400 mt-1">Risk Category</p>
              </div>
            </GlassCard>
            <GlassCard className="p-5 text-center fade-in-up" style={{ animationDelay: "0.1s" }}>
              <div>
                <div className="w-10 h-10 rounded-xl bg-gradient-to-br from-violet-400 to-purple-500 flex items-center justify-center mx-auto mb-3">
                  <Cpu className="w-5 h-5 text-white" />
                </div>
                <p className="text-sm font-bold text-slate-800">v1.0.0</p>
                <p className="text-xs text-slate-400 mt-1">Model Version</p>
              </div>
            </GlassCard>
          </div>

          {/* Tabs */}
          <div className="flex gap-2 mb-6 glass rounded-2xl p-2 overflow-x-auto">
            {[
              { id: "overview" as Tab, label: "Risk Overview", icon: <TrendingUp className="w-4 h-4" /> },
              { id: "explanation" as Tab, label: "Why This Result?", icon: <Lightbulb className="w-4 h-4" /> },
              { id: "whatif" as Tab, label: "What-If Analysis", icon: <TrendingUp className="w-4 h-4" /> },
              { id: "history" as Tab, label: "Session History", icon: <Clock className="w-4 h-4" /> },
            ].map((t) => (
              <div
                key={t.id}
                className={`tab-item flex items-center gap-2 whitespace-nowrap ${tab === t.id ? "active" : ""}`}
                onClick={() => setTab(t.id)}
              >
                {t.icon}
                {t.label}
              </div>
            ))}
          </div>

          {/* Tab content */}
          {tab === "overview" && (
            <div className="space-y-6 fade-in">
              {/* Risk meter card */}
              <GlassCard strong className="p-8">
                <div className="flex items-center gap-3 mb-6">
                  <div className="w-10 h-10 rounded-xl gradient-bg flex items-center justify-center">
                    <Brain className="w-5 h-5 text-white" />
                  </div>
                  <div>
                    <h2 className="font-bold text-slate-800">Estimated Cardiovascular Risk</h2>
                    <p className="text-xs text-slate-400">Based on the information provided</p>
                  </div>
                </div>
                <RiskMeter riskScore={result.riskScore} riskLevel={result.riskLevel} />
                <div className="section-divider my-6" />
                <p className="text-sm text-slate-600 leading-relaxed text-center">{result.prediction}</p>
              </GlassCard>

              {/* Patient input profile */}
              <GlassCard className="p-6">
                <div className="flex items-center gap-3 mb-5">
                  <div className="w-9 h-9 rounded-xl bg-sky-100 flex items-center justify-center">
                    <User className="w-5 h-5 text-sky-600" />
                  </div>
                  <h2 className="font-bold text-slate-800">Patient Input Profile</h2>
                </div>
                <div className="grid grid-cols-2 md:grid-cols-3 lg:grid-cols-4 gap-3">
                  {inputFields.map((field, i) => (
                    <div key={i} className="glass-subtle rounded-xl p-3 fade-in-up" style={{ animationDelay: `${i * 0.04}s`, opacity: 0 }}>
                      <div className="flex items-center gap-2 mb-1">
                        <span className="text-sky-400">{field.icon}</span>
                        <span className="text-xs text-slate-400">{field.label}</span>
                      </div>
                      <p className="text-sm font-medium text-slate-700 truncate">{field.value}</p>
                    </div>
                  ))}
                </div>
              </GlassCard>

              {/* Recommendations */}
              <GlassCard className="p-6">
                <div className="flex items-center gap-3 mb-5">
                  <div className="w-9 h-9 rounded-xl bg-amber-100 flex items-center justify-center">
                    <Lightbulb className="w-5 h-5 text-amber-600" />
                  </div>
                  <h2 className="font-bold text-slate-800">Recommendations</h2>
                </div>
                <ul className="space-y-3">
                  {result.recommendations.map((rec, i) => (
                    <li key={i} className="flex items-start gap-3 text-sm text-slate-600 fade-in-up" style={{ animationDelay: `${i * 0.06}s`, opacity: 0 }}>
                      <div className="w-6 h-6 rounded-lg bg-amber-50 flex items-center justify-center flex-shrink-0 mt-0.5">
                        <span className="text-amber-600 text-xs font-bold">{i + 1}</span>
                      </div>
                      <span className="leading-relaxed">{rec}</span>
                    </li>
                  ))}
                </ul>
              </GlassCard>

              {/* Report download */}
              <GlassCard className="p-6 flex items-center justify-between">
                <div className="flex items-center gap-4">
                  <div className="w-12 h-12 rounded-xl bg-gradient-to-br from-sky-400 to-sky-600 flex items-center justify-center">
                    <FileText className="w-6 h-6 text-white" />
                  </div>
                  <div>
                    <h3 className="font-bold text-slate-800">Assessment Report</h3>
                    <p className="text-sm text-slate-400">Download a complete text report of this assessment</p>
                  </div>
                </div>
                <Button onClick={handleDownloadReport} icon={<Download className="w-4 h-4" />}>
                  Download
                </Button>
              </GlassCard>
            </div>
          )}

          {tab === "explanation" && (
            <div className="space-y-6 fade-in">
              <GlassCard strong className="p-6 md:p-8">
                <div className="flex items-center gap-3 mb-2">
                  <div className="w-10 h-10 rounded-xl bg-gradient-to-br from-amber-400 to-orange-500 flex items-center justify-center">
                    <Lightbulb className="w-5 h-5 text-white" />
                  </div>
                  <div>
                    <h2 className="font-bold text-slate-800">Why This Result?</h2>
                    <p className="text-xs text-slate-400">Feature-level contribution analysis (SHAP-style)</p>
                  </div>
                </div>
                <p className="text-sm text-slate-500 mb-6 leading-relaxed">
                  Each bar shows how much that individual health characteristic moved the model's
                  prediction away from a healthy baseline. Red bars increase risk, green bars decrease it.
                </p>
                <FeatureContributions contributions={result.contributions} />
              </GlassCard>

              <GlassCard className="p-6">
                <div className="flex items-center gap-3 mb-4">
                  <div className="w-9 h-9 rounded-xl bg-violet-100 flex items-center justify-center">
                    <Cpu className="w-5 h-5 text-violet-600" />
                  </div>
                  <h2 className="font-bold text-slate-800">Model Transparency</h2>
                </div>
                <div className="grid grid-cols-2 md:grid-cols-4 gap-3">
                  <div className="glass-subtle rounded-xl p-4">
                    <p className="text-xs text-slate-400 mb-1">Model</p>
                    <p className="text-sm font-medium text-slate-700">Logistic Regression</p>
                  </div>
                  <div className="glass-subtle rounded-xl p-4">
                    <p className="text-xs text-slate-400 mb-1">Version</p>
                    <p className="text-sm font-medium text-slate-700">{result.modelVersion}</p>
                  </div>
                  <div className="glass-subtle rounded-xl p-4">
                    <p className="text-xs text-slate-400 mb-1">Feature Schema</p>
                    <p className="text-sm font-medium text-slate-700">v1.0 (11 features)</p>
                  </div>
                  <div className="glass-subtle rounded-xl p-4">
                    <p className="text-xs text-slate-400 mb-1">Timestamp</p>
                    <p className="text-sm font-medium text-slate-700">{new Date(result.timestamp).toLocaleTimeString()}</p>
                  </div>
                </div>
              </GlassCard>

              <GlassCard subtle className="p-5">
                <div className="flex items-start gap-3">
                  <ShieldCheck className="w-5 h-5 text-teal-500 flex-shrink-0 mt-0.5" />
                  <p className="text-xs text-slate-500 leading-relaxed">
                    These contributions are computed by comparing each feature's actual value against
                    a healthy baseline and measuring the model's probability shift. They are mathematical
                    attributions, not causal medical explanations.
                  </p>
                </div>
              </GlassCard>
            </div>
          )}

          {tab === "whatif" && (
            <div className="fade-in">
              <GlassCard strong className="p-6 md:p-8">
                <div className="flex items-center gap-3 mb-2">
                  <div className="w-10 h-10 rounded-xl bg-gradient-to-br from-sky-400 to-teal-500 flex items-center justify-center">
                    <TrendingUp className="w-5 h-5 text-white" />
                  </div>
                  <div>
                    <h2 className="font-bold text-slate-800">What If?</h2>
                    <p className="text-xs text-slate-400">Explore hypothetical model changes</p>
                  </div>
                </div>
                <p className="text-sm text-slate-500 mb-6 leading-relaxed">
                  Adjust the sliders below to see how changing individual health parameters
                  would affect the model's risk estimate.
                </p>
                <WhatIfSimulator originalInput={input} originalResult={result} />
              </GlassCard>
            </div>
          )}

          {tab === "history" && (
            <div className="fade-in">
              <div className="flex items-center justify-between mb-4">
                <h2 className="font-bold text-slate-800">Recent Assessments (This Session)</h2>
                {predictions.length > 0 && (
                  <button
                    onClick={clearHistory}
                    className="flex items-center gap-1.5 text-sm text-red-500 hover:text-red-600 font-medium transition-colors"
                  >
                    <Trash2 className="w-4 h-4" /> Clear
                  </button>
                )}
              </div>
              {predictions.length === 0 ? (
                <GlassCard subtle className="p-12 text-center">
                  <div className="w-16 h-16 rounded-2xl bg-slate-100 flex items-center justify-center mx-auto mb-4">
                    <Clock className="w-8 h-8 text-slate-300" />
                  </div>
                  <h3 className="text-lg font-bold text-slate-600 mb-2">No History Yet</h3>
                  <p className="text-sm text-slate-400">Your assessment history for this session will appear here.</p>
                </GlassCard>
              ) : (
                <div className="space-y-3">
                  {predictions.map((pred, i) => (
                    <GlassCard key={pred.id} className="p-5 flex items-center gap-4 fade-in-up" >
                      <div className={`w-12 h-12 rounded-xl ${
                        pred.riskLevel === "Low" ? "risk-low" :
                        pred.riskLevel === "Moderate" ? "risk-moderate" :
                        pred.riskLevel === "High" ? "risk-high" : "risk-veryhigh"
                      } flex items-center justify-center flex-shrink-0`}
                      style={{ opacity: 0, animationDelay: `${i * 0.05}s` }}>
                        <span className="text-white text-xs font-bold">{pred.riskScore.toFixed(0)}%</span>
                      </div>
                      <div className="flex-1 min-w-0">
                        <div className="flex items-center gap-2">
                          <span className="font-bold text-slate-800">{pred.riskLevel}</span>
                          <span className="text-sm text-sky-600 font-medium">{pred.riskScore.toFixed(1)}%</span>
                        </div>
                        <p className="text-xs text-slate-400 truncate">{pred.prediction}</p>
                        <p className="text-xs text-slate-300 mt-1">
                          {new Date(pred.timestamp).toLocaleString()}
                        </p>
                      </div>
                      <ChevronRight className="w-5 h-5 text-slate-300 flex-shrink-0" />
                    </GlassCard>
                  ))}
                </div>
              )}
            </div>
          )}

          {/* Disclaimer footer */}
          <div className="mt-8">
            <GlassCard subtle className="p-5 flex items-start gap-3">
              <ShieldCheck className="w-5 h-5 text-teal-500 flex-shrink-0 mt-0.5" />
              <p className="text-xs text-slate-500 leading-relaxed">
                CardioSense AI produces machine-learning-based estimates. It does not provide definitive
                medical diagnosis, treatment recommendations, or professional medical advice. AI can assist
                understanding — clinical decisions belong to qualified healthcare professionals.
              </p>
            </GlassCard>
          </div>
        </div>
      </div>
    </div>
  );
}
